// Generates packages/core/src/data/countries.ts from i18n-iso-countries (MIT).
// Run with `npm run countries`. The output is committed so the core has no runtime dependency.
import { createRequire } from 'node:module';
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const countries = require('i18n-iso-countries');
const pkg = JSON.parse(
  readFileSync(new URL('../node_modules/i18n-iso-countries/package.json', import.meta.url)),
);

const names = {};
for (const alpha3 of Object.keys(countries.getAlpha3Codes()).sort()) {
  const name = countries.getName(alpha3, 'en', { select: 'official' });
  if (name) names[alpha3] = name;
}

const out = new URL('../packages/core/src/data/countries.ts', import.meta.url);
mkdirSync(new URL('.', out), { recursive: true });
const body = Object.entries(names)
  .map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`)
  .join('\n');
writeFileSync(
  out,
  `// GENERATED by scripts/generate-countries.mjs — do not edit by hand.
// Source: i18n-iso-countries ${pkg.version} (MIT License, Copyright (c) 2016 widdix GmbH),
// English names. See DATA_LICENSES.md.
export const ISO_COUNTRIES: Readonly<Record<string, string>> = {
${body}
};
`,
);
console.log(`wrote ${Object.keys(names).length} countries`);
